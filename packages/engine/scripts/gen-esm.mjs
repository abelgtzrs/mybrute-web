// Wraps the vendored original scripts as ES modules WITHOUT changing a byte of their source.
// Each original is a UMD-style IIFE that writes to `exports`/`module.exports` when those exist;
// the wrapper provides local ones and re-exports what the script attached.
// Run: npm run gen -w @mybrute/engine   (tests check the output is up to date)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const vendor = join(here, "../vendor");
const outDir = join(here, "../src/generated");

const header = (file) => `// GENERATED from vendor/${file} by scripts/gen-esm.mjs. Do not edit.\n/* eslint-disable */\n// @ts-nocheck\n`;

const targets = [
  // Haxe output: (function($hx_exports,$global){...})(typeof exports != "undefined" ? exports : window, ...)
  { file: "glad.js", pre: "const exports = {};\n", post: "\nexport const GladAPI = exports.GladAPI;\nexport const Gladiator = exports.Gladiator;\n" },
  { file: "fight.js", pre: "const exports = {};\n", post: "\nexport const FightAPI = exports.FightAPI;\n" },
  // hand-written UMD: module.exports = api when `module` exists
  { file: "labrute.js", pre: "const module = { exports: {} };\n", post: "\nexport const LaBrute = module.exports;\n" },
  { file: "fightlog.js", pre: "const module = { exports: {} };\n", post: "\nexport const FightLog = module.exports;\n" },
  // inventory.js attaches to `window` (or globalThis) and reads root.LaBrute at call time; give it a private root
  { file: "inventory.js", pre: 'import { LaBrute } from "./labrute.js";\nconst window = { LaBrute };\n', post: "\nexport const Inventory = window.Inventory;\n" },
];

for (const t of targets) {
  const src = readFileSync(join(vendor, t.file), "utf8");
  const begin = "// ---- vendor source begins ----\n", end = "\n// ---- vendor source ends ----\n";
  writeFileSync(join(outDir, t.file), header(t.file) + t.pre + begin + src + end + t.post);
  // typed views live in src/vendor.ts; the stub only lets consumers import without allowJs
  const names = [...t.post.matchAll(/export const (\w+)/g)].map((m) => m[1]);
  writeFileSync(join(outDir, t.file.replace(/\.js$/, ".d.ts")), `// GENERATED by scripts/gen-esm.mjs. Do not edit.\n${names.map((n) => `export declare const ${n}: any;\n`).join("")}`);
}
// Every reward a level-up can offer, read from glad.js's own Data.BONUS_WEIGHTS table (kind, id, base weight).
const glad = readFileSync(join(vendor, "glad.js"), "utf8");
const table = glad.slice(glad.indexOf("Data.BONUS_WEIGHTS = ["));
const bonuses = [...table.slice(0, table.indexOf("];")).matchAll(/\{ id : _\$Bonus\.(\w+)\(_\$\w+\.(\w+)\), w : (\d+)\}/g)]
  .map(([, kind, id, w]) => ({ kind, id, weight: Number(w) }));
if (bonuses.length < 50) throw new Error("couldn't read Data.BONUS_WEIGHTS from glad.js");
writeFileSync(join(outDir, "bonuses.js"), `// GENERATED from vendor/glad.js (Data.BONUS_WEIGHTS) by scripts/gen-esm.mjs. Do not edit.\nexport const BONUSES = ${JSON.stringify(bonuses, null, 1)};\n`);
writeFileSync(join(outDir, "bonuses.d.ts"), `// GENERATED by scripts/gen-esm.mjs. Do not edit.\nexport declare const BONUSES: { kind: "Permanent" | "Super" | "Followers" | "Talent" | "Weapons"; id: string; weight: number }[];\n`);

console.log("generated", targets.map((t) => t.file).join(", "), `and ${bonuses.length} bonuses`);
